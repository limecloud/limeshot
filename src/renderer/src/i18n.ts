export function resolveLocale(language: string): Locale {
  const normalized = language.toLowerCase();
  if (normalized.startsWith('zh-tw') || normalized.startsWith('zh-hk') || normalized.startsWith('zh-hant')) return 'zh-TW';
  if (normalized.startsWith('ja')) return 'ja-JP';
  if (normalized.startsWith('ko')) return 'ko-KR';
  if (normalized.startsWith('en')) return 'en-US';
  return 'zh-CN';
}

export function createTranslator(locale: Locale): (key: TranslationKey) => string {
  return (key) => dictionaries[locale][key];
}

export function isTranslationKey(key: string): key is TranslationKey {
  return key in zhCN;
}

